package ru.mirea.hotel.backend.domain;

/**
 * Три уровня доступа. Сервер проверяет роль сам, независимо от того,
 * какие кнопки показал или скрыл клиент.
 */
public enum Role {
    /** Просмотр: бронирования, гости, номера, аналитика. */
    VIEWER,
    /** Менеджер (администратор ресепшена): создание и изменение бронирований и гостей. */
    MANAGER,
    /** Администратор системы: справочник номеров, пользователи, аудит, окончательное удаление. */
    ADMIN
}
