package hotel.model;

/**
 * Статус бронирования номера.
 * Используется как обязательное перечисление (enum) в предметной модели.
 */
public enum BookingStatus {
    CREATED,     // бронирование только создано
    CONFIRMED,   // подтверждено администратором гостиницы
    CHECKED_IN,  // гость заселился в номер
    CHECKED_OUT, // гость выселился, бронирование завершено
    CANCELLED    // бронирование отменено
}
